// Copies the texts the browser planner shares with the app (wizard, schedule
// editor, print layout) from the app's i18n into src/planner/i18n/app.<lang>.js.
// Run after the app's texts change:  node scripts/sync-planner-texts.mjs [path to app]
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { pathToFileURL } from 'node:url'

const appSrc = path.resolve(process.argv[2] || '../waschplan/frontend/src')
const out = path.resolve('src/planner/i18n')
const pick = (o = {}, keys) => Object.fromEntries(keys.filter((k) => k in o).map((k) => [k, o[k]]))

for (const lang of ['de', 'en', 'fr', 'it']) {
  const d = (await import(pathToFileURL(path.join(appSrc, 'i18n', `${lang}.js`)))).default
  const texts = {
    common: pick(d.common, ['add', 'apply', 'back', 'cancel', 'change', 'close', 'howItWorks', 'loading', 'next', 'undo']),
    confirm: pick(d.confirm, ['startOver']),
    setup: pick(d.setup, ['progress', 'stepOf', 'steps', 'savedLocally', 'startOver', 'block', 'house', 'machines', 'times', 'plan']),
    slots: d.slots,
    plan: d.plan,
    rule: d.rule,
    kind: d.kind,
    print: d.print,
    rules: pick(d.rules, ['weeks', 'days', 'threeMonths', 'unit', 'sum']),
  }
  const file = path.join(out, `app.${lang}.js`)
  writeFileSync(file, `// Generated by scripts/sync-planner-texts.mjs from the app's i18n (${lang}.js). Do not edit:\n// change the texts in the app, or override them in ${lang}.js next to this file.\nexport default ${JSON.stringify(texts, null, 2)}\n`)
  console.log('wrote', path.relative(process.cwd(), file))
}
